/**
 * ROTA2-ADAPTIVE-HUNTER-04 — the closed missions' records this mission moved, field by field.
 *
 * The adaptive Hunter changes production on Routes 2/3 (games there take other turns) and the solvers' state (the last
 * direction), so some evidence that earlier missions keep in `--check` mode measures something different today. Those
 * records were updated only where present-day `--check` needs them; this tool lists, for each, every VERDICT field
 * (run metadata excluded) whose value at the mission's base (ec3e564 — the last commit that wrote them) differs from
 * the working tree's, so what each mission measured at its own commit stays on record next to what it measures now.
 *
 * It reads `git show ec3e564:<file>` and the working tree; it writes the note only with `--write`.
 *
 * Usage:
 *   node tools/validation/rota2-adaptive-hunter-superseded.mjs           # print the tables; exit 1 if the note is stale
 *   node tools/validation/rota2-adaptive-hunter-superseded.mjs --write   # (re)write the note's generated part
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const BASE = "ec3e564a47b7fad8421bfae34fcbda32acebe043";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "..");
const NOTE = "docs/archive/rota2-adaptive-hunter-04/superseded-records.md";
const GENERATED = "<!-- generated by tools/validation/rota2-adaptive-hunter-superseded.mjs — do not edit below -->";
/** Every record of an earlier mission this mission's tree rewrote, and the dotted paths that are run metadata there. */
export const SUPERSEDED = [
  { file: "docs/archive/rota2-dynamic-traps-01/dynamic-traps-tests.json", metadata: ["run"], validator: "rota2-dynamic-traps-tests.mjs" },
  { file: "docs/archive/rota2-dynamic-traps-01/census.json", metadata: ["run"], validator: "rota2-dynamic-traps-census.mjs" },
  { file: "docs/archive/rota2-dependent-objectives-02/dependent-objectives-tests.json", metadata: ["run"], validator: "rota2-dependent-objectives-tests.mjs" },
  { file: "docs/archive/rota2-dependent-objectives-02/census.json", metadata: ["run"], validator: "rota2-dependent-objectives-census.mjs" },
  { file: "docs/archive/rota2-sentinel-solver-fidelity-03/fidelity-tests.json", metadata: ["run"], validator: "rota2-sentinel-solver-fidelity-tests.mjs" },
  { file: "docs/archive/rota2-sentinel-solver-fidelity-03/counterfactual-f5826b2.json", metadata: ["run"], validator: "rota2-sentinel-solver-fidelity-tests.mjs --rev=f5826b2" },
  { file: "docs/archive/rota2-sentinel-solver-fidelity-03/mutants.json", metadata: ["run"], validator: "rota2-sentinel-solver-fidelity-tests.mjs --mutants" },
  { file: "docs/archive/rota2-sentinel-solver-fidelity-03/census.json", metadata: ["run"], validator: "rota2-sentinel-solver-fidelity-census.mjs" },
];

const show = (spec) => {
  try {
    return execFileSync("git", ["show", spec], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  } catch {
    return null;
  }
};
const strip = (value, metadata) => {
  const copy = JSON.parse(JSON.stringify(value));
  for (const dotted of metadata) {
    const parts = dotted.split(".");
    let node = copy;
    for (let i = 0; i < parts.length - 1 && node; i += 1) node = node[parts[i]];
    if (node) delete node[parts.at(-1)];
  }
  return copy;
};
function leaves(value, prefix, out) {
  if (value !== null && typeof value === "object") {
    const keys = Object.keys(value);
    if (keys.length === 0) out.set(prefix, JSON.stringify(value));
    for (const k of keys) leaves(value[k], prefix ? `${prefix}.${k}` : k, out);
  } else out.set(prefix, JSON.stringify(value));
  return out;
}
const cell = (text) => (text === undefined ? "(absent)" : `\`${text.length > 90 ? `${text.slice(0, 87)}…` : text}\``.replace(/\|/g, "\\|"));

export function supersededTables() {
  const sections = [];
  for (const { file, metadata, validator } of SUPERSEDED) {
    const before = show(`${BASE}:${file}`);
    const nowPath = path.join(ROOT, file);
    const now = fs.existsSync(nowPath) ? fs.readFileSync(nowPath, "utf8") : null;
    if (before === null || now === null) {
      sections.push(`### \`${file}\`\n\n${before === null ? "absent at the base" : "absent in the working tree"}.\n`);
      continue;
    }
    const a = leaves(strip(JSON.parse(before), metadata), "", new Map());
    const b = leaves(strip(JSON.parse(now), metadata), "", new Map());
    const paths = [...new Set([...a.keys(), ...b.keys()])].filter((p) => a.get(p) !== b.get(p)).sort();
    const head = `### \`${file}\`\n\nValidator: \`node tools/validation/${validator}\`. Verdict fields that differ: **${paths.length}**.\n`;
    if (!paths.length) {
      sections.push(`${head}\nUnchanged.\n`);
      continue;
    }
    const rows = paths.map((p) => `| \`${p}\` | ${cell(a.get(p))} | ${cell(b.get(p))} |`);
    sections.push(`${head}\n| field | at ec3e564 (the record) | this tree |\n| --- | --- | --- |\n${rows.join("\n")}\n`);
  }
  return sections.join("\n");
}

function main() {
  const tables = supersededTables();
  const notePath = path.join(ROOT, NOTE);
  const current = fs.existsSync(notePath) ? fs.readFileSync(notePath, "utf8").replace(/\r\n/g, "\n") : "";
  const preamble = current.includes(GENERATED) ? current.slice(0, current.indexOf(GENERATED)) : "# Superseded records\n\n";
  const next = `${preamble}${GENERATED}\n\n${tables}`;
  if (process.argv.includes("--write")) {
    fs.mkdirSync(path.dirname(notePath), { recursive: true });
    fs.writeFileSync(notePath, next);
    console.log(`wrote ${NOTE}`);
    return 0;
  }
  console.log(tables);
  const fresh = current === next;
  console.log(fresh ? "SUPERSEDED_NOTE_CURRENT" : "SUPERSEDED_NOTE_STALE (run with --write)");
  return fresh ? 0 : 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) process.exitCode = main();
